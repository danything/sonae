/** 選べる声 1 つ (キャラクターとスタイルの組。id は VOICEVOX のスタイルの id) */
export interface Voice {
  id: number;
  /** キャラクターの名前 (クレジットに使う) */
  name: string;
  style: string;
}

/** 声の情報 (`GET /api/speech`) */
export interface SpeechInfo {
  /** VOICEVOX のエンジンにつながっている */
  available: boolean;
  /** まだ選んでいないときの声 (`VOICEVOX_SPEAKER`) */
  defaultSpeaker: number;
  /** この家で読む声 (サーバーに 1 つ。全部の端末で同じ) */
  voice: number;
  voices: Voice[];
}

/** クレジット (「VOICEVOX:剣崎雌雄」)。出典と注意の窓に、読む声を出す */
export const creditOf = (v: Pick<Voice, "name">) => `VOICEVOX:${v.name}`;

/** 選択肢の表示 (「剣崎雌雄 (ノーマル)」) */
export const voiceLabel = (v: Voice) => `${v.name} (${v.style})`;
